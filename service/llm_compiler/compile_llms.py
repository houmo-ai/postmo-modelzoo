    core_str = f"{core_num}cores" if core_num > 1 else f"{core_num}core"

    if docker_flag and args.upload is True:
        version_str = f"{target}-v{version}" if args.release is True else ""
        if version_str:
            model_name = "deepseek" if "deepseek" in model_name else model_name
        current_dt = datetime.now()
        current_ts = (
            current_dt.strftime("%Y%m%d_%H%M%S") if not version_str else f"v{version}"
        )
        today = current_dt.strftime("%Y%m%d")
        if quant_flag:
            # Publish quantized model (will upload to Jfrog)
            host_quant_dir = host_result_dir + "/quant_results/hmquant"
            quant_file_name = f"hmquant_{target}_{model_name}_{model_size}_"
            if prefill_len > 0:
                quant_file_name += f"{prefill_len}_"
            if context_len > 0:
                quant_file_name += f"{context_str}_"
            quant_file_name += f"{current_ts}.zip"

            md5sum_quant, jfrog_path_quant = _publish_model(
                today,
                quant_file_name,
                host_quant_dir,
                host_result_dir,
                model_name,
                host_log_file,
                version_str,
            )
            if jfrog_path_quant is None or md5sum_quant is None:
                logger.error(f"Failed to publish quant model {host_quant_dir}.")
                exit(44)
            else:
                logger.info(
                    f"#hm upload to jfrog success with quantpath:{jfrog_path_quant}"
                )
        elif jfrog_path_quant:
            compressed_quant_file = (
                f"{host_result_dir}/quant_results/"
                + quant_model_path.rsplit("/", 1)[-1]
            )
            md5sum_quant = _get_md5sum(compressed_quant_file)

        # Upload the compiled files only when disabling quant.
        if args.forced_compile or not quant_flag:
            # publish compiled model (will upload to Jfrog)
            host_compile_dir = host_result_dir + "/compile_results"
            compiled_file_name = f"hmm_{target}_{model_name}_{model_size}_"
            if prefill_len > 0:
                compiled_file_name += f"{prefill_len}_"
            if context_len > 0:
                compiled_file_name += f"{context_str}_"
            if batch > 0:
                compiled_file_name += f"b{batch}_"
            compiled_file_name += f"{chip_str}_{core_str}_{current_ts}.zip"
            md5sum_compile, jfrog_path_compile = _publish_model(
                today,
                compiled_file_name,
                host_compile_dir,
                host_result_dir,
                model_name,
                host_log_file,
                version_str,
                [".hmm", ".hmms", ".pt"],
            )
            if jfrog_path_compile is None or md5sum_compile is None:
                logger.error(f"Failed to publish compiled model {host_compile_dir}.")
                exit(4)
            else:
                logger.info(
                    f"#hm upload to jfrog success with path:{jfrog_path_compile}"
                )

            # Update published model table: published_models.csv
            publish_dt = current_dt.strftime("%Y%m%d %H:%M:%S")
            model_id = f"{os.getpid()}-{current_ts}"
            version_str = f"v{version}"
            new_model = {
                "model_id": model_id,
                "model_name": model_name,
                "model_size": model_size,
                "prefill_length": prefill_len,
                "context_length": context_len,
                "version": version_str,
                "target": target,
                "device_num": device_num,
                "core_num": core_num,
                "publish_time": publish_dt,
                "model_md5sum": md5sum_compile,
                "quant_model_md5sum": md5sum_quant,
                "model_path": jfrog_path_compile,
                "quant_model_path": jfrog_path_quant,
            }
            ret = _update_model_table(new_model)
            if ret is False:
                logger.info("## hm enter here5")
                exit(5)

    if args.perf_config and target == "xh2" and device_num <= 2:
        perf_mode = model_info[model_name_ori][model_size]["perf"]

        if compiled_file_name is None:
            compiled_file_name = f"{target}_{model_name}_{model_size}_"
            if prefill_len > 0:
                compiled_file_name += f"{prefill_len}_"
            if context_len > 0:
                compiled_file_name += f"{context_str}_"
            if batch > 0:
                compiled_file_name += f"b{batch}_"
            compiled_file_name += f"{chip_str}_{core_str}_v{version}"

        compile_results_dir = f"{host_result_dir}/compile_results"

        if perf_mode in ["llm_perf"]:
            new_stream = {
                "ModelName": compiled_file_name,
                "prefill": f"{compile_results_dir}/{model_name}_prefill.hmm",
                "decode": f"{compile_results_dir}/{model_name}_decode.hmm",
                "embedding": f"{compile_results_dir}/hmquant/quant_embedding.bin",
                "input": 256,
                "stop": 2048,
                "ndevices": device_num if device_num > 1 else 1,
                "loop": 2,
                "batch": batch,
            }
            if context_len < (2048 + 256) and context_len >= (1024 + 256):
                new_stream["stop"] = 1024
            elif context_len > 0 and context_len < (1024 + 256):
                new_stream["input"] = int(context_len * 0.2)
                new_stream["stop"] = context_len - new_stream["input"]
            if "-vl" in model_name_ori:
                new_stream["visual"] = f"{compile_results_dir}/{model_name}_visual.hmm"
            if device_num > 1:
                new_stream["prefill"] = new_stream["prefill"] + "s"
                new_stream["decode"] = new_stream["decode"] + "s"
                if "visual" in new_stream:
                    new_stream["visual"] = new_stream["visual"] + "s"

            cfg_path = args.perf_config

        elif perf_mode in ["tcim_perf"]:
            hmm_list = glob.glob(f"{compile_results_dir}/*.hmm")
            new_stream = {
                "ModelName": compiled_file_name,
                "hmm_list": hmm_list,
                "samples": 100,
                "devices": device_num if device_num > 1 else 1,
                "batch": batch,
                "name": model_name_ori,
                "loops": 1,
                "warm_up": 1,
            }
            # _tcim.json
            cfg_path = args.perf_config.replace(".json", "_tcim.json")

        elif perf_mode in ["demo"]:
            new_stream = {
                "ModelName": compiled_file_name,
                "model_dir": model_dir,
                "hmm_dir": compile_results_dir,
                "ndevices": device_num if device_num > 1 else 1,
            }
            # _demo.json
            cfg_path = args.perf_config.replace(".json", "_demo.json")

        if os.path.exists(cfg_path):
            try:
                with open(cfg_path, "r", encoding="utf-8") as f:
                    cfg_data = json.load(f)
            except json.JSONDecodeError:
                logger.error(
                    f"{cfg_path} is not a valid JSON file. A new file will be created."
                )
                cfg_data = {"Streams": []}
        else:
            logger.error(f"{cfg_path} does not exist. A new file will be created.")
            cfg_data = {"Streams": []}

        if "Streams" not in cfg_data or not isinstance(cfg_data["Streams"], list):
            logger.warning("JSON structure is abnormal. Reset Streams to list.")
            cfg_data["Streams"] = []

        cfg_data["Streams"].append(new_stream)

        with open(cfg_path, "w", encoding="utf-8") as f:
            json.dump(cfg_data, f, indent=2, ensure_ascii=False, sort_keys=False)
        logger.info(
            f"Successful addition of configuration. The current total number of Perf models:{len(cfg_data['Streams'])}"
        )

    del_suffixes = args.delete_filetypes
    delete_files(host_result_dir, [".zip"])
    if len(del_suffixes) > 0:
        logger.info(f"Start to clear result files {del_suffixes}")
        delete_files(host_result_dir, del_suffixes)
        quant_work_dir = f"{script_dir}/../../{model_dir}/work_dirs"
        if os.path.exists(quant_work_dir):
            delete_files(quant_work_dir, del_suffixes)

    if not docker_flag:
        logger.info("### something error in docker container")
        exit(-1)
