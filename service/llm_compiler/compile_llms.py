def _get_jfrog_info(jfrog_url) -> bool:
    """Check if a JFrog URL is accessible.

    Args:
        jfrog_url (str): URL to check

    Returns:
        bool: True if accessible, False otherwise
    """

    jfrog_base, jfrog_tail = jfrog_url.split("artifactory/")
    logger.info(f"_get_jfrog_info, jfrog_base: {jfrog_base}, jfrog_tail:{jfrog_tail}")
    jfrog_base = jfrog_base + "artifactory"
    file_info_path = f"{jfrog_base}/api/storage/{jfrog_tail}"
    response = requests.get(file_info_path)
    logger.info(
        f"_get_jfrog_info, ret: {response.status_code}, file_info_path:{file_info_path}"
    )
    if response.status_code == 200:
        return True

    return False


def _check_args(args: dict) -> bool:
    """Validate the provided command line arguments.

    Args:
        args: Arguments object containing parsed command line options

    Returns:
        bool: True if arguments are valid, False otherwise
    """
    from packaging import version

    if args.target not in ["xh1", "xh2"]:
        logger.error(f"Invalid houmo target {args.target}.")
        return False

    if (
        args.quant_model_path
        and "http" in args.quant_model_path
        and _get_jfrog_info(args.quant_model_path) is False
    ):
        logger.error(f"Invalid quant model path {args.quant_model_path}")
        return False

    if args.core_num <= 0 or args.core_num > 4:
        logger.error(f"Invalid core_num {args.core_num}, only supports [1, 4].")
        return False

    if args.device_num < -1 or args.device_num > 32:
        logger.error(f"Invalid device_num {args.device_num}, only supports [0, 32].")
        return False

    if args.batch < 0 or args.batch > 32:
        logger.error(f"Invalid batch number {args.batch}, only supports [1, 32].")
        return False

    try:
        xh1_min_ver = version.parse("2.4.2")
        xh2_min_ver = version.parse("0.3.0")
        ver = version.parse(args.version)
        if (args.target == "xh1" and ver < xh1_min_ver) or (
            args.target == "xh2" and ver < xh2_min_ver
        ):
            logger.error(f"Unsupported version {args.version} on {args.target}.")
            return False
    except version.InvalidVersion as e:
        logger.error(f"Invalid version {args.version}, error msg: {str(e)}")
        return False

    if args.context_length > 0 and args.context_length % 128 != 0:
        logger.error(
            f"Invalid context_length {args.context_length}, it needs to be divisible by 1024."
        )
        return False

    logger.info(
        "\n***** Compilation Configs *****\n"
        "-- Model name: %s \n"
        "-- Model size: %s \n"
        "-- DaDao Software version: %s \n"
        "-- Quantized model path: %s \n"
        "-- Prefill length: %d \n"
        "-- Context length: %d \n"
        "-- Houmo target: %s \n"
        "-- Batch: %d \n"
        "-- Device num: %d \n"
        "-- Core num: %d \n"
        "-- J: %d \n"
        "-- Flash Attention: %d \n"
        "-- Save results to %s\n"
        "-- Task Id: %s \n",
        args.model_name,
        args.model_size,
        args.version,
        args.quant_model_path,
        args.prefill_length,
        args.context_length,
        args.target,
        args.batch,
        args.device_num,
        args.core_num,
        args.j,
        args.flash_attention,
        args.result_dir,
        args.task_id,
    )

    return True


def _upload_model(
    date_str: str,
    model_name: str,
    model_file: str,
    file_name: str,
    local_md5: str,
    log_file: str,
    version_str: str,
) -> None | str:
    """Upload a model file to JFrog repository.

    Uploads the specified model file to the JFrog repository with MD5 checksum
    verification to prevent duplicate uploads. Also uploads associated CPP zip file
    if it exists.

    Args:
        date_str (str): Date string for organizing uploads
        model_name (str): Name of the model
        model_file (str): Path to the local model file
        file_name (str): Name to use for the uploaded file
        local_md5 (str): MD5 checksum of the local file
        log_file (str): Path to the log file
        version_str (str): Version string for release uploads

    Returns:
        str: JFrog path of the uploaded model, or None if upload failed
    """

    if not JFROG_CREDENTIALS_RELEASE and not JFROG_CREDENTIALS_GENMDS:
        logger.error(
            "Missing required JFrog credentials environment variables!\n"
            "Please set:\n"
            "  - JFROG_CREDENTIALS_RELEASE (format: username:password)\n"
            "  - JFROG_CREDENTIALS_GENMDS (format: username:password)"
        )
        return None

    # Select JFrog credentials and repository path based on version flag
    if version_str:
        jfrog_repo_url = RELEASE_MODELZOO_URL
        jfrog_suffix = f"{version_str}/{model_name}/{file_name}"
        jfrog_credentials = JFROG_CREDENTIALS_RELEASE
    else:
        jfrog_repo_url = MODELZOO_URL
        jfrog_suffix = f"{model_name}/{date_str}/{file_name}"
        jfrog_credentials = JFROG_CREDENTIALS_GENMDS

    # Construct full JFrog file path and API path for MD5 check
    jfrog_file_path = f"{jfrog_repo_url}/{jfrog_suffix}"
    try:
        # Split JFrog URL to build storage API path (handle edge cases)
        jfrog_base, jfrog_tail = jfrog_repo_url.split("artifactory/")
        jfrog_base = f"{jfrog_base}artifactory"
        file_info_path = f"{jfrog_base}/api/storage/{jfrog_tail}/{jfrog_suffix}"
    except ValueError as e:
        logger.error(
            f"Invalid JFrog repository URL format: {jfrog_repo_url}. Error: {e}"
        )
        return None

    # Check if file already exists in JFrog (MD5 verification)
    try:
        response = requests.get(file_info_path, timeout=10)
        response.raise_for_status()  # Raise exception for HTTP errors

        url_md5 = response.json()["checksums"]["md5"]
        if local_md5 == url_md5:
            logger.info(f"{jfrog_file_path} ({url_md5}) already exists. Skip upload.")
            return jfrog_file_path
    except requests.exceptions.RequestException as e:
        # Ignore 404 (file not found) - proceed to upload
        if response.status_code != 404:
            logger.warning(
                f"Failed to check existing file in JFrog: {e}. Proceeding to upload."
            )
    except KeyError as e:
        logger.error(
            f"Invalid response format from JFrog API (missing {e}). Proceeding to upload."
        )

    # Upload main model file
    upload_cmds = ["curl", "-u", jfrog_credentials, "-T", model_file, jfrog_file_path]
    if not execute_cmd(upload_cmds, log_file):
        logger.error(f"Failed to upload model file: {model_file}")
        return None

    # Upload associated CPP zip file (if exists)
    cpp_zip_file = f"{model_file[:-4]}_cpps.zip"
    if os.path.exists(cpp_zip_file):
        jfrog_cpp_zip_path = f"{jfrog_file_path[:-4]}_cpps.zip"

        # Adjust path for release version CPP files
        if version_str:
            jfrog_cpp_zip_path = jfrog_cpp_zip_path.replace(
                "/Dadao/models/", "/toolchain/release/models_outdated/"
            )

        # Execute CPP file upload
        cpp_upload_cmds = [
            "curl",
            "-u",
            jfrog_credentials,
            "-T",
            cpp_zip_file,
            jfrog_cpp_zip_path,
        ]
        if not execute_cmd(cpp_upload_cmds, log_file):
            logger.error(f"Failed to upload CPP zip file: {cpp_zip_file}")
            return None

    return jfrog_file_path


def _get_md5sum(model_file):
    """Calculate the MD5 checksum of a file.

    Args:
        model_file (str): Path to the file to check

    Returns:
        str: MD5 checksum of the file, or None if calculation failed
    """
    if not os.path.isfile(model_file):
        logger.error(f"Error: {model_file} not exist.")
        return None

    try:
        result = subprocess.run(
            ["md5sum", model_file],
            check=True,
            stdout=subprocess.PIPE,
            stderr=subprocess.PIPE,
            text=True,
        )
        md5_sum = result.stdout.split()[0]
        return md5_sum

    except subprocess.CalledProcessError as e:
        logger.error(f"Failed to execute md5sum: {e.stderr}")
        return None
    except Exception as e:
        logger.error(f"Unknown error: {str(e)}")
        return None


def _update_model_table(new_model) -> bool:
    """Update the published models table with new model information.

    Adds the new model entry to the published models CSV file, updating existing
    entries with the same path but different MD5 checksums.

    Args:
        new_model (dict): Dictionary containing model metadata

    Returns:
        bool: True if update was successful, False otherwise
    """
    import pandas as pd

    model_csv = f"{script_dir}/published_models.csv"
    try:
        model_df = pd.read_csv(model_csv)
        target_md5 = new_model["model_md5sum"]
        target_jfrog_path = new_model["model_path"]
        condition_contains = model_df["model_path"].str.contains(
            target_jfrog_path, na=False
        )
        condition_md5_mismatch = model_df["model_md5sum"] != target_md5
        rows_to_delete = condition_contains & condition_md5_mismatch
        model_df = model_df[~rows_to_delete]

        new_model_df = pd.DataFrame(new_model, index=[0])
        model_df = pd.concat([model_df, new_model_df], ignore_index=True)
        model_df.to_csv(model_csv, index=False)
        logger.info(f"Append a new model {new_model} into {model_csv}.")
        return True
    except Exception as e:
        logger.error(f"Error occurred: {str(e)}")
    return False


def _publish_model(
    date_str: str,
    model_file_name: str,
    host_model_dir: str,
    host_result_dir: str,
    model_name: str,
    host_log_file: str,
    version_str: str = None,
    extensions: list = list(),
) -> Tuple[str, str]:
    """Publish a model by compressing and uploading it to JFrog.

    Compresses the model directory into a ZIP file, calculates its MD5 checksum,
    and uploads it to the JFrog repository.

    Args:
        date_str (str): Date string for organizing uploads
        model_file_name (str): Name for the compressed model file
        host_model_dir (str): Directory containing the model to publish
        host_result_dir (str): Directory to store the compressed file
        model_name (str): Name of the model
        host_log_file (str): Path to the log file
        version_str (str): Version string for release uploads
        extensions (list): List of file extensions to include in compression

    Returns:
        Tuple[str, str]: MD5 checksum and JFrog path of the published model,
                         or (None, None) if publication failed
    """
    compressed_model = f"{host_result_dir}/{model_file_name}"
    if os.path.exists(compressed_model):
        logger.warning(
            f"The compressed model file already exists. Please clean it up first: {compressed_model}"
        )
    else:
        logger.info(f"Compress model folder {host_model_dir} -> {compressed_model}")
        ret = compress_to_zip(host_model_dir, compressed_model, extensions)
        if ret is False:
            return None, None
    model_md5 = _get_md5sum(compressed_model)
    model_jfrog_path = _upload_model(
        date_str,
        model_name,
        compressed_model,
        model_file_name,
        model_md5,
        host_log_file,
        version_str,
    )
    logger.info(f"Publish info: Jfrog path: {model_jfrog_path}, md5sum: {model_md5}")

    return model_md5, model_jfrog_path


